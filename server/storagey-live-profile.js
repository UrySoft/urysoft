import { liveFlag } from './live-flag.js';
// Explicit, isolated live configuration. There is no fallback to test credentials.
export function liveProfile(env){
  if(env.STORAGEY_LIVE_PAYMENTS!=='enabled'||!liveFlag(env, 'STORAGEY', 'SELLER_READY')||!liveFlag(env, 'STORAGEY', 'GOOGLE_PUBLIC'))return null;
  const names=['STORAGEY_LIVE_DB','STORAGEY_LIVE_PAYPAL_CLIENT_ID','STORAGEY_LIVE_PAYPAL_CLIENT_SECRET','STORAGEY_LIVE_PAYPAL_PLAN_ID','STORAGEY_LIVE_PAYPAL_WEBHOOK_ID','STORAGEY_LIVE_GOOGLE_CLIENT_ID','STORAGEY_LIVE_LICENSE_PRIVATE_KEY'];
  if(names.some(name=>!env[name]))return null;
  if(env.STORAGEY_LIVE_DB===env.FOLDERY_LIVE_DB
      ||env.STORAGEY_LIVE_PAYPAL_PLAN_ID===env.FOLDERY_LIVE_PAYPAL_PLAN_ID
      ||env.STORAGEY_LIVE_LICENSE_PRIVATE_KEY===env.FOLDERY_LIVE_LICENSE_PRIVATE_KEY)return null;
  if(env.STORAGEY_LIVE_DB===env.PREMIUM_DB||env.STORAGEY_LIVE_LICENSE_PRIVATE_KEY===env.STORAGEY_LICENSE_PRIVATE_KEY||env.STORAGEY_LIVE_PAYPAL_CLIENT_ID===env.PAYPAL_CLIENT_ID||env.STORAGEY_LIVE_PAYPAL_CLIENT_SECRET===env.PAYPAL_CLIENT_SECRET||[env.GOOGLE_CLIENT_ID,env.STORAGEY_GOOGLE_CLIENT_ID].includes(env.STORAGEY_LIVE_GOOGLE_CLIENT_ID))return null;
  return {
    PREMIUM_DB:env.STORAGEY_LIVE_DB,
    STORAGEY_PREMIUM_ENABLED:'live',PAYPAL_ENVIRONMENT:'live',STORAGEY_LIVE_PAYMENTS:'enabled',
    PAYPAL_CLIENT_ID:env.STORAGEY_LIVE_PAYPAL_CLIENT_ID,PAYPAL_CLIENT_SECRET:env.STORAGEY_LIVE_PAYPAL_CLIENT_SECRET,
    PAYPAL_PLAN_ID:env.STORAGEY_LIVE_PAYPAL_PLAN_ID,PAYPAL_WEBHOOK_ID:env.STORAGEY_LIVE_PAYPAL_WEBHOOK_ID,
    STORAGEY_GOOGLE_CLIENT_ID:env.STORAGEY_LIVE_GOOGLE_CLIENT_ID,STORAGEY_LICENSE_PRIVATE_KEY:env.STORAGEY_LIVE_LICENSE_PRIVATE_KEY
  };
}
