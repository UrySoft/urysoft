// Explicit, isolated live configuration. There is no fallback to test credentials.
export function liveProfile(env){
  if(env.TECLAIRC_LIVE_PAYMENTS!=='enabled'||env.TECLAIRC_LIVE_SELLER_READY!=='yes'||env.TECLAIRC_LIVE_GOOGLE_PUBLIC!=='yes')return null;
  const names=['TECLAIRC_LIVE_DB','TECLAIRC_LIVE_PAYPAL_CLIENT_ID','TECLAIRC_LIVE_PAYPAL_CLIENT_SECRET','TECLAIRC_LIVE_PAYPAL_PLAN_ID','TECLAIRC_LIVE_PAYPAL_WEBHOOK_ID','TECLAIRC_LIVE_GOOGLE_CLIENT_ID','TECLAIRC_LIVE_LICENSE_PRIVATE_KEY'];
  if(names.some(name=>!env[name]))return null;
  const isolatedFields=['DB','PAYPAL_PLAN_ID','LICENSE_PRIVATE_KEY'];
  for(const product of ['FOLDERY','WIDGERY','STORAGEY','MINAIRO']){
    if(isolatedFields.some(field=>env['TECLAIRC_LIVE_'+field]===env[product+'_LIVE_'+field]))return null;
  }
  if(env.TECLAIRC_LIVE_DB===env.PREMIUM_DB||env.TECLAIRC_LIVE_LICENSE_PRIVATE_KEY===env.TECLAIRC_LICENSE_PRIVATE_KEY||env.TECLAIRC_LIVE_PAYPAL_CLIENT_ID===env.PAYPAL_CLIENT_ID||env.TECLAIRC_LIVE_PAYPAL_CLIENT_SECRET===env.PAYPAL_CLIENT_SECRET||[env.GOOGLE_CLIENT_ID,env.TECLAIRC_GOOGLE_CLIENT_ID].includes(env.TECLAIRC_LIVE_GOOGLE_CLIENT_ID))return null;
  return {
    PREMIUM_DB:env.TECLAIRC_LIVE_DB,
    TECLAIRC_PREMIUM_ENABLED:'live',PAYPAL_ENVIRONMENT:'live',TECLAIRC_LIVE_PAYMENTS:'enabled',
    PAYPAL_CLIENT_ID:env.TECLAIRC_LIVE_PAYPAL_CLIENT_ID,PAYPAL_CLIENT_SECRET:env.TECLAIRC_LIVE_PAYPAL_CLIENT_SECRET,
    PAYPAL_PLAN_ID:env.TECLAIRC_LIVE_PAYPAL_PLAN_ID,PAYPAL_WEBHOOK_ID:env.TECLAIRC_LIVE_PAYPAL_WEBHOOK_ID,
    TECLAIRC_GOOGLE_CLIENT_ID:env.TECLAIRC_LIVE_GOOGLE_CLIENT_ID,TECLAIRC_LICENSE_PRIVATE_KEY:env.TECLAIRC_LIVE_LICENSE_PRIVATE_KEY
  };
}
